#!/usr/bin/env python3
"""
Pre-synthesize natural human-like Mandarin TTS (.mp3) for the 5 Fengshui books
in index.html (RAW) using edge-tts (zh-CN-YunyangNeural, rate=-10%).
Outputs books/audio/*.mp3 and books/audio-manifest.js.
"""
import asyncio
import json
import subprocess
from pathlib import Path
import edge_tts

ROOT = Path(__file__).resolve().parent
BOOKS_DIR = ROOT / "books"
AUDIO_DIR = BOOKS_DIR / "audio"
VOICE = "zh-CN-YunyangNeural"
RATE = "-10%"
CONC = 6


def extract_raw():
    node_code = r"""
const fs=require('fs'),vm=require('vm');
const html=fs.readFileSync(process.argv[1],'utf8');
const m=html.match(/const RAW = \{[\s\S]*?\n\};/);
const ctx={};
vm.runInNewContext(m[0].replace(/^const /,'var '),ctx);
process.stdout.write(JSON.stringify(ctx.RAW));
"""
    out = subprocess.check_output(["node", "-e", node_code, str(ROOT / "index.html")], text=True)
    return json.loads(out)


def fix_fengshui_tts(text: str) -> str:
    # Subtle pronunciation hints for classical Fengshui terms
    for old, new in [
        ("朝山", "潮山"),
        ("朝水", "潮水"),
        ("朝迎", "潮迎"),
        ("相朝", "相潮"),
        ("朝拜", "潮拜"),
        ("干山", "乾山"),
        ("干水", "乾水"),
    ]:
        text = text.replace(old, new)
    return text


def build_tracks():
    raw = extract_raw()
    manifest = {}
    jobs = []
    for key, book in raw.items():
        paras = book["paras"]
        tracks = []
        # Group paragraphs into ~120-180 char chunks (break on song headers in batiao)
        chunks = []
        cur = []
        cur_len = 0
        for idx, p in enumerate(paras):
            is_hdr = book.get("type") == "batiao" and p.startswith("第") and "歌" in p[:5]
            if cur and (is_hdr or cur_len + len(p) > 160):
                chunks.append(cur)
                cur = []
                cur_len = 0
            cur.append((idx, p))
            cur_len += len(p)
        if cur:
            chunks.append(cur)

        for ci, ch in enumerate(chunks):
            s_idx = ch[0][0]
            e_idx = ch[-1][0]
            tts = fix_fengshui_tts("。".join(p.rstrip("。；，") for _, p in ch) + "。")
            fn = f"{key}-{ci:02d}.mp3"
            tracks.append({
                "file": fn,
                "startIdx": s_idx,
                "endIdx": e_idx,
                "label": f"第{ci+1}/{len(chunks)}节",
            })
            jobs.append((tts, fn))
        manifest[key] = tracks
    return manifest, jobs


async def synth_all(jobs):
    AUDIO_DIR.mkdir(parents=True, exist_ok=True)
    todo = [(t, fn) for (t, fn) in jobs if not (AUDIO_DIR / fn).exists() or (AUDIO_DIR / fn).stat().st_size == 0]
    print(f"Voice={VOICE} Rate={RATE} | Total={len(jobs)} | Todo={len(todo)}")
    sem = asyncio.Semaphore(CONC)
    fails = []

    async def one(text, fn, i):
        async with sem:
            out = AUDIO_DIR / fn
            for attempt in range(3):
                try:
                    comm = edge_tts.Communicate(text, VOICE, rate=RATE)
                    await comm.save(str(out))
                    if out.exists() and out.stat().st_size > 0:
                        if (i + 1) % 10 == 0 or i + 1 == len(todo):
                            print(f"  done {i+1}/{len(todo)} ({fn})")
                        return
                except Exception as e:
                    if attempt == 2:
                        fails.append((fn, str(e)))
                    await asyncio.sleep(1.5 * (attempt + 1))

    await asyncio.gather(*(one(t, fn, i) for i, (t, fn) in enumerate(todo)))
    if fails:
        raise RuntimeError(f"Failed {len(fails)} tracks: {fails[:5]}")


def main():
    manifest, jobs = build_tracks()
    asyncio.run(synth_all(jobs))
    out_js = BOOKS_DIR / "audio-manifest.js"
    out_js.write_text(
        "/* Generated by gen_book_audio.py */\nwindow.YANGONG_BOOK_AUDIO="
        + json.dumps(manifest, ensure_ascii=False, separators=(",", ":"))
        + ";\n",
        encoding="utf-8",
    )
    total_kb = sum((AUDIO_DIR / fn).stat().st_size for _, fn in jobs) / 1024
    print(f"Manifest written: {out_js.name} | {len(jobs)} mp3s | {total_kb/1024:.2f} MB")


if __name__ == "__main__":
    main()
